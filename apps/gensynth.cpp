// Generates SYNTHETIC daily bars for several market regimes. These are NOT market data.
// Usage: mc_gensynth <out_dir> [seed]
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <string>
#include "mc/exchange.hpp"
#include "mc/replay.hpp"

namespace {
int civil_from_days(long z) {
  z += 719468;
  const long era = (z >= 0 ? z : z - 146096) / 146097;
  const unsigned doe = static_cast<unsigned>(z - era * 146097);
  const unsigned yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  int y = static_cast<int>(yoe) + static_cast<int>(era) * 400;
  const unsigned doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  const unsigned mp = (5 * doy + 2) / 153;
  const unsigned d = doy - (153 * mp + 2) / 5 + 1;
  const unsigned m = mp < 10 ? mp + 3 : mp - 9;
  y += m <= 2;
  return y * 10000 + static_cast<int>(m) * 100 + static_cast<int>(d);
}
double gauss(mc::Rng& r) {
  const double u1 = std::max(r.uni(), 1e-12), u2 = r.uni();
  return std::sqrt(-2.0 * std::log(u1)) * std::cos(6.283185307179586 * u2);
}
struct Regime { double mu, vol, revert; };   // annual drift, annual vol, mean-reversion speed
double tick(double p) { return std::max(0.05, std::round(p * 20.0) / 20.0); }
}  // namespace

int main(int argc, char** argv) {
  if (argc < 2) { std::fprintf(stderr, "usage: mc_gensynth <out_dir> [seed]\n"); return 2; }
  const std::string dir = argv[1];
  const std::uint64_t seed = argc > 2 ? std::strtoull(argv[2], nullptr, 10) : 42;
  std::filesystem::create_directories(dir);
  const Regime calm{0.06, 0.10, 0}, wild{0.0, 0.45, 0}, up{0.25, 0.18, 0}, down{-0.20, 0.20, 0}, range{0, 0.20, 0.05};
  struct Sym { const char* name; double start; Regime seq[4]; };
  const Sym syms[] = {
      {"SYN_CALM", 1200, {calm, calm, calm, calm}},   {"SYN_VOLATILE", 800, {wild, wild, wild, wild}},
      {"SYN_TREND_UP", 600, {up, up, up, up}},        {"SYN_TREND_DOWN", 2400, {down, down, down, down}},
      {"SYN_RANGE", 1500, {range, range, range, range}}, {"SYN_MIXED", 1000, {calm, up, wild, down}},
  };
  const int n = 1500;
  const double dt = 1.0 / 252.0;
  std::uint64_t k = 0;
  for (const Sym& s : syms) {
    mc::Rng rng(seed * 1000003ULL + (++k));
    std::ofstream f(dir + "/" + s.name + ".csv");
    f << "# SYNTHETIC DATA generated by mc_gensynth (seed " << seed << "). NOT market data.\n";
    f << "date,open,high,low,close,volume\n";
    double c = s.start;
    const double anchor = std::log(s.start);
    long day = mc::days_from_civil(20200101);
    for (int i = 0; i < n; ++i, ++day) {
      while (((day % 7) + 7) % 7 == 2 || ((day % 7) + 7) % 7 == 3) ++day;   // skip Saturday and Sunday
      const Regime& g = s.seq[(i / 250) % 4];
      const double sd = g.vol * std::sqrt(dt);
      const double o = c * std::exp(0.3 * sd * gauss(rng));
      double x = std::log(o) + (g.mu - 0.5 * g.vol * g.vol) * dt + sd * gauss(rng);
      if (g.revert > 0) x += g.revert * (anchor - x);
      const double cl = std::exp(x);
      const double hi = std::max(o, cl) * (1.0 + 0.5 * sd * std::fabs(gauss(rng)));
      const double lo = std::min(o, cl) * (1.0 - 0.5 * sd * std::fabs(gauss(rng)));
      const double to = tick(o), tc = tick(cl);
      const double th = std::max({tick(hi), to, tc}), tl = std::min({tick(lo), to, tc});
      const long vol = 100000 + static_cast<long>(rng.uni() * 900000.0);
      char buf[160];
      std::snprintf(buf, sizeof buf, "%d,%.2f,%.2f,%.2f,%.2f,%ld\n", civil_from_days(day), to, th, tl, tc, vol);
      f << buf;
      c = tc;
    }
  }
  std::printf("SYNTHETIC data written to %s (6 symbols x %d bars, seed %llu)\n", dir.c_str(), n, static_cast<unsigned long long>(seed));
  return 0;
}
